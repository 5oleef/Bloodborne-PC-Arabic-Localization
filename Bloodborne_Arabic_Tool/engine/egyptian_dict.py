def get_shaped_overrides(mode='egyptian'):
    """
    يرجع قواميس التعديل بعد تطبيق التشكيل وعكس الاتجاه (BiDi Reshaped)
    mode: 'egyptian' أو 'standard'
    """
    if mode != 'egyptian':
        return {}, {}
    
    shaped_menu = {}
    for (group_id, message_id), raw_text in EGYPTIAN_MENU_OVERRIDES.items():
        shaped_menu[(group_id, message_id)] = shape_bidi(raw_text)
        
    shaped_items = {}
    for (group_id, message_id), raw_text in EGYPTIAN_ITEM_OVERRIDES.items():
        shaped_items[(group_id, message_id)] = shape_bidi(raw_text)
        
    return shaped_menu, shaped_items
