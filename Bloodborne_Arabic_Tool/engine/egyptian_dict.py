"""
قاموس التعريب المصري للعبة Bloodborne PC
يحول النصوص والمصطلحات إلى اللهجة العامية المصرية مع التشكيل والاتجاه الصحيح (Reshaping & BiDi)
"""
import arabic_reshaper
from bidi.algorithm import get_display

def shape_bidi(text):
    """
    إعادة تشكيل وعكس النص العربي ليتوافق مع محرك الخطوط في Scaleform (Bloodborne)
    يحافظ على السطور الجديدة والمسافات والرموز الإنجليزية
    """
    if not text:
        return text
    lines = text.split('\n')
    reshaped_lines = []
    for line in lines:
        if any('\u0600' <= c <= '\u06FF' or '\uFB50' <= c <= '\uFEFC' for c in line):
            # Reshape standard Arabic to Presentation Forms
            reshaped = arabic_reshaper.reshape(line)
            # Reorder for RTL display
            bidi_text = get_display(reshaped)
            reshaped_lines.append(bidi_text)
        else:
            reshaped_lines.append(line)
    return '\n'.join(reshaped_lines)


